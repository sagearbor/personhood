// Write the personhood Active Authentication circuits (aa/lib + one small
// bin per variant) into a zkPassport circuits checkout, next to its own
// libraries, so build.sh compiles them like any other variant. Called by
// build.sh; Apache-2.0 (see aa/lib/src/lib.nr).
//
//   node aa/gen.mjs <circuits checkout> <variant path>...
//
// Variant paths under bin/personhood-aa/ are generated; others are ignored.
// Names:
//   aa_absent                              EF.SOD lists no DG15
//   aa_dg_<h>_rsa_<bits>_<h'>              DG15 hashed with <h>; RSA-<bits> AA,
//                                          ISO/IEC 9796-2 scheme 1 with <h'>
//   aa_dg_<h>_ecdsa_p256_<h'>              DG15 hashed with <h>; ECDSA P-256 AA
//                                          (plain r||s) over <h'>(challenge)
import fs from "fs"
import path from "path"
import { fileURLToPath } from "url"

const HERE = path.dirname(fileURLToPath(import.meta.url))
export const HASHES = {
  sha1: { bytes: 20, id: 0x33 },
  sha224: { bytes: 28, id: 0x38 },
  sha256: { bytes: 32, id: 0x34 },
  sha384: { bytes: 48, id: 0x36 },
  sha512: { bytes: 64, id: 0x35 },
}
export const RSA_BITS = [1024, 1536, 2048, 3072]
const PREFIX = "bin/personhood-aa/"

export function parseVariant(name) {
  if (name === "aa_absent") return { kind: "absent" }
  const m = name.match(/^aa_dg_(sha\d+)_(rsa_(\d+)|ecdsa_p256)_(sha\d+)$/)
  if (!m || !HASHES[m[1]] || !HASHES[m[4]]) throw new Error(`unknown AA variant ${name}`)
  if (m[3] && !RSA_BITS.includes(Number(m[3]))) throw new Error(`unsupported RSA size in ${name}`)
  return { kind: m[3] ? "rsa" : "ecdsa", dgHash: m[1], bits: m[3] ? Number(m[3]) : 256, aaHash: m[4] }
}

const COMMON_ARGS = `    comm_in: pub Field,
    aa_challenge: pub Field,
    salt_in: Field,
    dg1: DG1Data,
    signed_attributes: SignedAttrsData,
    signed_attributes_size: Field,
    e_content: EContentData,
    private_nullifier: Field,`

const COMMON_CHECK = `    check_id_commitment(
        comm_in,
        salt_in,
        dg1,
        signed_attributes,
        signed_attributes_size,
        e_content,
        private_nullifier,
    );`

function mainNr(name) {
  const v = parseVariant(name)
  const header = `// Generated by tools/zk-circuits/aa/gen.mjs (personhood, Apache-2.0). Do not edit.\n`
  const uses = ["check_id_commitment", "challenge_bytes"]
  if (v.kind === "absent") {
    uses.push("assert_dg15_not_listed")
    return `${header}use personhood_aa::{${uses.join(", ")}};
use utils::types::{DG1Data, EContentData, SignedAttrsData};

fn main(
${COMMON_ARGS}
) {
${COMMON_CHECK}
    // The challenge is public for a uniform shape; a passport without DG15
    // has nothing to sign it with. Still range-checked to 8 bytes.
    let _ = challenge_bytes(aa_challenge);
    assert_dg15_not_listed(e_content);
}
`
  }
  const dgFn = `${v.dgHash}_of`
  const aaFn = `${v.aaHash}_of`
  uses.push("assert_dg15_listed", "dg15_length", "DG15_MAX_LENGTH", dgFn)
  if (aaFn !== dgFn) uses.push(aaFn)
  if (v.kind === "rsa") {
    const k = v.bits / 8
    const h = HASHES[v.aaHash]
    uses.push("parse_rsa_dg15", "rsa_aa_recover", "rsa_aa_message", "rsa_aa_check_digest")
    return `${header}use personhood_aa::{${uses.join(", ")}};
use utils::types::{DG1Data, EContentData, SignedAttrsData};

fn main(
${COMMON_ARGS}
    dg15: [u8; DG15_MAX_LENGTH],
    aa_signature: [u8; ${k}],
    aa_redc_param: [u8; ${k + 1}],
) {
${COMMON_CHECK}
    let dg15_len = dg15_length(dg15);
    assert_dg15_listed(e_content, ${dgFn}(dg15, dg15_len));
    let (modulus, exponent) = parse_rsa_dg15::<_, ${k}>(dg15, dg15_len);
    let (rep, trailer_len) =
        rsa_aa_recover::<${k}, ${h.bytes}>(modulus, exponent, aa_signature, aa_redc_param, 0x${h.id.toString(16)});
    let (msg, msg_len) = rsa_aa_message::<${k}, ${h.bytes}>(rep, trailer_len, challenge_bytes(aa_challenge));
    rsa_aa_check_digest::<${k}, ${h.bytes}>(rep, trailer_len, ${aaFn}(msg, msg_len));
}
`
  }
  const h = HASHES[v.aaHash]
  const eFn = h.bytes <= 32 ? "ecdsa_e_short" : "ecdsa_e_long"
  uses.push("parse_ec_dg15_p256", "verify_p256", eFn)
  return `${header}use personhood_aa::{${uses.join(", ")}};
use utils::types::{DG1Data, EContentData, SignedAttrsData};

fn main(
${COMMON_ARGS}
    dg15: [u8; DG15_MAX_LENGTH],
    aa_signature: [u8; 64],
) {
${COMMON_CHECK}
    let dg15_len = dg15_length(dg15);
    assert_dg15_listed(e_content, ${dgFn}(dg15, dg15_len));
    let (x, y) = parse_ec_dg15_p256(dg15, dg15_len);
    let challenge = challenge_bytes(aa_challenge);
    verify_p256(x, y, aa_signature, ${eFn}(${aaFn}(challenge, 8)));
}
`
}

function nargoToml(name) {
  return `[package]
name = "${name}"
type = "bin"
authors = ["personhood"]
compiler_version = ">=1.0.0"
license = "Apache-2.0"

[dependencies]
personhood_aa = { path = "../../../lib/personhood-aa" }
utils = { path = "../../../lib/utils" }
`
}

function writeIfChanged(file, text) {
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8") === text) return
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, text)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [repo, ...variants] = process.argv.slice(2)
  if (!repo) throw new Error("usage: node aa/gen.mjs <circuits checkout> <variant path>...")
  const noir = path.resolve(repo, "src/noir")
  const libDir = path.join(noir, "lib/personhood-aa")
  writeIfChanged(path.join(libDir, "Nargo.toml"), fs.readFileSync(path.join(HERE, "lib/Nargo.toml"), "utf8"))
  writeIfChanged(path.join(libDir, "src/lib.nr"), fs.readFileSync(path.join(HERE, "lib/src/lib.nr"), "utf8"))
  let n = 0
  for (const v of variants) {
    if (!v.startsWith(PREFIX)) continue
    const name = v.slice(PREFIX.length)
    writeIfChanged(path.join(noir, v, "Nargo.toml"), nargoToml(name))
    writeIfChanged(path.join(noir, v, "src/main.nr"), mainNr(name))
    n++
  }
  console.log(`personhood AA: ${n} variants generated`)
}
